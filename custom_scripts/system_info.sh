#!/usr/bin/env sh
# =============================================================================
# system_info.sh — 系统常规巡检（每次都输出，始终推送）
# =============================================================================
# 用法：在 HOSTS_JSON 的主机条目中设置：
#   "script_file": "/scripts/system_info.sh"
# =============================================================================

echo "=== 系统信息 ==="
uname -a

echo ""
echo "=== CPU / 内存 ==="
ps -o pid,%cpu,%mem,comm | head -10

echo ""
echo "=== 磁盘使用 ==="
df -h

echo ""
echo "=== 当前时间 ==="
date